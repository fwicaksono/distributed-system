"""Request ID propagation, access logging and HTTP metrics — as pure ASGI middleware.

Pure ASGI (instead of BaseHTTPMiddleware) avoids per-request task overhead and plays
well with streaming responses.
"""

from __future__ import annotations

import logging
import re
import time
import uuid

from starlette.types import ASGIApp, Message, Receive, Scope, Send

from app.core.logging import request_id_ctx
from app.core.metrics import HTTP_IN_PROGRESS, HTTP_LATENCY, HTTP_REQUESTS

logger = logging.getLogger("app.access")

REQUEST_ID_HEADER = b"x-request-id"
_VALID_REQUEST_ID = re.compile(r"^[A-Za-z0-9._-]{8,64}$")
_SKIP_ACCESS_LOG = {"/health/live", "/metrics"}


class RequestContextMiddleware:
    def __init__(self, app: ASGIApp) -> None:
        self.app = app

    async def __call__(self, scope: Scope, receive: Receive, send: Send) -> None:
        if scope["type"] != "http":
            await self.app(scope, receive, send)
            return

        # Reuse the ID generated by Nginx ($request_id) so one ID spans proxy + API + worker.
        incoming = dict(scope["headers"]).get(REQUEST_ID_HEADER, b"").decode("latin-1")
        request_id = incoming if _VALID_REQUEST_ID.match(incoming) else uuid.uuid4().hex
        token = request_id_ctx.set(request_id)

        status_code = 500
        started = time.perf_counter()

        async def send_wrapper(message: Message) -> None:
            nonlocal status_code
            if message["type"] == "http.response.start":
                status_code = message["status"]
                message.setdefault("headers", []).append(
                    (REQUEST_ID_HEADER, request_id.encode("latin-1"))
                )
            await send(message)

        HTTP_IN_PROGRESS.inc()
        try:
            await self.app(scope, receive, send_wrapper)
        finally:
            HTTP_IN_PROGRESS.dec()
            duration = time.perf_counter() - started
            # Route template (e.g. /api/v1/tasks/{task_id}) keeps metric cardinality bounded.
            route = scope.get("route")
            route_label = getattr(route, "path", None) or "unmatched"
            method = scope["method"]
            HTTP_REQUESTS.labels(method, route_label, str(status_code)).inc()
            HTTP_LATENCY.labels(method, route_label).observe(duration)
            if scope["path"] not in _SKIP_ACCESS_LOG:
                logger.info(
                    "request",
                    extra={
                        "method": method,
                        "path": scope["path"],
                        "route": route_label,
                        "status": status_code,
                        "duration_ms": round(duration * 1000, 2),
                        "client": (scope.get("client") or ("-",))[0],
                    },
                )
            request_id_ctx.reset(token)
